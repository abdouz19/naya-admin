const revenueByMonth = [
  { month: 'Mars', revenue: 810 },
  { month: 'Avr.', revenue: 945 },
  { month: 'Mai', revenue: 1080 },
  { month: 'Juin', revenue: 1190 },
  { month: 'Juil.', revenue: 1295 },
  { month: 'Aout', revenue: 1420 },
];

export function getMockRevenueStats(): RevenueStats {
  const active = mockSubscriptions.filter((s) => s.status === 'active');
  const trials = mockSubscriptions.filter((s) => s.status === 'trial');
  const cancelled = mockSubscriptions.filter((s) => s.status === 'cancelled');
  const expired = mockSubscriptions.filter((s) => s.status === 'expired');

  const mrr = active.reduce((sum, s) => sum + s.amount, 0);
  const arr = mrr * 12;
  const totalRevenue = revenueByMonth.reduce((sum, m) => sum + m.revenue, 0);
  const activeSubscriptions = active.length;
  const churnRate = cancelled.length / (active.length + cancelled.length + expired.length);
  const averageRevenuePerUser = mrr / (activeSubscriptions || 1);
  // Trial conversions: out of all past trials (expired + active that were once trial), simulate 62%
  const trialConversions = 0.62;

  // New subscriptions this month (August 2026)
  const newSubscriptionsThisMonth = mockSubscriptions.filter((s) => {
    const started = new Date(s.started_at);
    return started.getMonth() === 7 && started.getFullYear() === 2026;
  }).length;

  // Cancelled this month
  const cancelledThisMonth = mockSubscriptions.filter((s) => {
    if (!s.cancelled_at) return false;
    const cancelled = new Date(s.cancelled_at);
    return cancelled.getMonth() === 7 && cancelled.getFullYear() === 2026;
  }).length;

  // Plan distribution (active only)
  const planCounts: Record<string, number> = {};
  for (const s of active) {
    planCounts[s.plan] = (planCounts[s.plan] || 0) + 1;
  }
  const planDistribution = Object.entries(planCounts).map(([plan, count]) => ({
    plan,
    count,
  }));

  // Status distribution
  const statusCounts: Record<string, number> = {
    active: active.length,
    trial: trials.length,
    cancelled: cancelled.length,
    expired: expired.length,
  };
  const statusDistribution = Object.entries(statusCounts).map(
    ([status, count]) => ({ status, count }),
  );

  return {
    mrr,
    arr,
    totalRevenue,
    activeSubscriptions,
    churnRate,
    averageRevenuePerUser,
    trialConversions,
    revenueByMonth,
    planDistribution,
    statusDistribution,
    newSubscriptionsThisMonth,
    cancelledThisMonth,
  };
}
